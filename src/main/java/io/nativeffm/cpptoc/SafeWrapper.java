package io.nativeffm.cpptoc;

import io.nativeffm.cpptoc.Ast.*;
import io.nativeffm.cpptoc.Lexer.K;
import io.nativeffm.cpptoc.Lexer.Tok;

import java.io.*;
import java.nio.charset.StandardCharsets;
import java.util.*;
import java.util.stream.Collectors;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

import static io.nativeffm.cpptoc.Lexer.EOF;
import static io.nativeffm.cpptoc.Words.*;

/**
 * Writes the safe wrapper: <name>_safe.h (C) and <name>_safe.cpp (C++). For every function F of the bridged headers,
 * {@code int safe_F(<F's parameters>, R *result)} checks that references, by-value structs and arrays are not NULL,
 * calls F inside try/catch and returns a status code; the C++ helpers it uses are in safe_runtime.cpp.
 */
final class SafeWrapper {

    /** The headers-independent part of the .cpp: everything after the marker line of safe_runtime.cpp. */
    private static final String RUNTIME = runtime();

    private final Translation tr;

    SafeWrapper(Translation tr) {
        this.tr = tr;
    }

    private static String runtime() {
        try (InputStream in = SafeWrapper.class.getResourceAsStream("safe_runtime.cpp")) {
            if (in == null) throw new IllegalStateException("safe_runtime.cpp is missing next to SafeWrapper.java");
            String text = new String(in.readAllBytes(), StandardCharsets.UTF_8);
            return text.substring(text.indexOf('\n', text.indexOf("---- copied from here ----")) + 1);
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    /** The safe wrapper API in C: error codes, last_error_*, one wrapper per function, the layout probes. */
    String header(List<Fn> fns, List<StructDef> probed) {
        String guard = tr.baseName.toUpperCase().replaceAll("[^A-Z0-9]", "_") + "_SAFE_H";
        String p = tr.prefix;
        StringBuilder b = new StringBuilder("""
                /* %s_safe.h - safe wrapper API for %s, generated by CppToC. Do not edit.
                 *
                 * For every function F of the bridged headers:
                 *     int %sF(<F's parameters>, R *result);
                 * calls F and returns SAFE_OK, or an error code: no C++ exception or NULL reference gets through.
                 *   - C++ references are pointers; NULL is rejected (SAFE_NULL_ARGUMENT, F is not called), as it is for
                 *     structs passed by value (const pointers here) and for array parameters.
                 *   - const references to numbers and enums are passed by value.
                 *   - F's return value is stored in *result (if result is not NULL); there is no result parameter for void.
                 *   - after a failure, %slast_error_*() describe it, until the next failing call on the same thread.
                 * The line "@wraps <declaration>" above each function names the provider function it wraps.
                 */
                #ifndef %s
                #define %s

                """.formatted(tr.baseName, bridgedNames(), p, p, guard, guard));
        for (Header u : tr.selection.roots()) b.append("#include \"").append(Translation.cHeaderName(u.rel)).append("\"\n");
        b.append("""

                #ifdef __cplusplus
                extern "C" {
                #endif

                #define SAFE_OK 0                 /* the function returned normally */
                #define SAFE_NULL_ARGUMENT 1      /* a required pointer was NULL: the function was not called */
                #define SAFE_CPP_EXCEPTION 2      /* the function threw a std::exception (type and what() in the error details) */
                #define SAFE_UNKNOWN_EXCEPTION 3  /* the function threw something else */

                /* The last failure on the calling thread: the function's name, the exception type and its message. */
                const char *%1$slast_error_function(void);
                const char *%1$slast_error_type(void);
                const char *%1$slast_error_message(void);

                """.formatted(p));
        for (Fn f : fns) {
            b.append(condOpen(f.conds));
            b.append("/** @wraps ").append(wraps(f).replace("*/", "* /")).append(" */\n");
            b.append("int ").append(f.safeName).append('(').append(safeParams(f, true)).append(");\n");
            b.append(condClose(f.conds)).append('\n');
        }
        if (!probed.isEmpty()) {
            b.append("""
                    /* Layout probes: write sizeof, alignof and each field's offset (declaration order) as the C++ compiler
                     * sees them into out (at most max values); return the number of values. */
                    """);
            for (StructDef s : probed) {
                b.append(condOpen(s.conds)).append("int ").append(p).append("layout_").append(s.cName)
                        .append("(long long *out, int max);\n").append(condClose(s.conds));
            }
            b.append('\n');
        }
        return b.append("#ifdef __cplusplus\n}\n#endif\n\n#endif /* ").append(guard).append(" */\n").toString();
    }

    /** The safe wrapper in C++: the runtime (safe_runtime.cpp), then a wrapper per function and a probe per struct. */
    String source(List<Fn> fns, List<StructDef> probed) {
        String p = tr.prefix;
        StringBuilder b = new StringBuilder("""
                // %s_safe.cpp - safe wrapper for %s, generated by CppToC. Do not edit.
                //
                // Every provider function F gets an extern "C" wrapper %sF that checks its pointer arguments, calls F inside
                // try/catch and returns a status code (see %s_safe.h). Compile it with the same compiler family and C++
                // runtime as the provider's library, so that the provider's exceptions can be caught here.
                //
                // Every exception is caught. A std::exception, and the provider's types listed in --exceptions, are reported
                // with their type and message (SAFE_CPP_EXCEPTION); anything else with its type, and for a thrown string or
                // number its value (SAFE_UNKNOWN_EXCEPTION).

                """.formatted(tr.baseName, bridgedNames(), p, tr.baseName));
        for (Header u : tr.selection.roots()) b.append("#include \"").append(u.rel).append("\"\n");
        for (String h : tr.exceptionHeaders) b.append("#include \"").append(h).append("\"\n");
        if (!tr.exceptionTypes.isEmpty()) {
            b.append("""

                    // --exceptions: the provider's exception types, caught before std::exception and reported with their message.
                    #define SAFE_CATCH_MAPPED_EXCEPTIONS""");
            for (String[] x : tr.exceptionTypes) {
                String message = x[1] == null ? "\"\"" : "text(e." + x[1] + ")";
                b.append(" \\\n    catch (const ").append(x[0]).append("& e) {").append(" return fail(SAFE_CPP_EXCEPTION, function,")
                        .append(" type_name(typeid(e)), ").append(message).append("); }");
            }
            b.append('\n');
        }
        b.append('\n').append(RUNTIME).append('\n');
        for (String what : List.of("function", "type", "message")) {
            b.append(what.equals("function") ? "" : "\n").append("SAFE_API const char* ").append(p).append("last_error_")
                    .append(what).append("(void) noexcept {\n    return safe_detail::error_").append(what).append(".c_str();\n}\n");
        }
        for (Fn f : fns) wrapper(b, f);
        for (StructDef s : probed) probe(b, s);
        return b.toString();
    }

    /** safe_F: NULL checks, the call inside try/catch, the result through the last parameter. */
    private void wrapper(StringBuilder b, Fn f) {
        b.append('\n').append(condOpen(f.conds));
        if (!f.ns.isEmpty()) b.append(f.ns.stream().map(x -> "namespace " + x + " {").collect(Collectors.joining(" "))).append("\n\n");
        b.append("// ").append(wraps(f)).append('\n');
        b.append("SAFE_API int ").append(f.safeName).append('(').append(safeParams(f, false)).append(") noexcept {\n");
        String fname = '"' + f.qualified() + '"';
        for (Param p : f.params) {
            String what = p.byValueStruct ? "passed by value" : p.ref && !p.constRefValue ? "a C++ reference"
                    : required(f, p) && p.type.ptr() > 0 ? (tr.arrayParams.contains(p.name)
                    || tr.arrayParams.contains(f.name + "." + p.name) ? "an array" : "required") : null;
            if (what == null) continue;
            b.append("    if (").append(p.name).append(" == nullptr) return safe_detail::null_argument(")
                    .append(fname).append(", \"").append(p.name).append("\", \"").append(what).append("\");\n");
        }
        StringJoiner args = new StringJoiner(", ");
        for (Param p : f.params) args.add((p.byValueStruct || p.ref && !p.constRefValue ? "*" : "") + p.name);
        String call = "::" + f.qualified() + "(" + args + ")";
        b.append("    try {\n");
        if (hasResult(f)) {
            String r = resultName(f);
            b.append("        auto&& r$ = ").append(call).append(";\n");
            b.append("        if (").append(r).append(" != nullptr) *").append(r).append(" = ")
                    .append(f.ret.ref() ? "&r$" : "r$").append(";\n");
        } else {
            b.append("        ").append(call).append(";\n");
        }
        b.append("""
                        return SAFE_OK;
                    } catch (...) {
                        return safe_detail::caught(%s);
                    }
                }
                """.formatted(fname));
        if (!f.ns.isEmpty()) {
            b.append("\n").append("} ".repeat(f.ns.size()).strip()).append("  // namespace ").append(String.join("::", f.ns)).append('\n');
        }
        b.append(condClose(f.conds));
    }

    /** safe_layout_S: sizeof, alignof and each field's offsetof, as the C++ compiler sees them. */
    private void probe(StringBuilder b, StructDef s) {
        b.append('\n').append(condOpen(s.conds));
        b.append("SAFE_API int ").append(tr.prefix).append("layout_").append(s.cName).append("(long long* out, int max) noexcept {\n");
        b.append("    const long long values[] = {\n");
        b.append("        static_cast<long long>(sizeof(").append(s.cppName).append(")),\n");
        b.append("        static_cast<long long>(alignof(").append(s.cppName).append(")),\n");
        for (String field : s.fields) {
            b.append("        static_cast<long long>(offsetof(").append(s.cppName).append(", ").append(field).append(")),\n");
        }
        b.append("""
                    };
                    const int count = static_cast<int>(sizeof values / sizeof values[0]);
                    for (int i = 0; out != nullptr && i < count && i < max; i++) out[i] = values[i];
                    return count;
                }
                """);
        b.append(condClose(s.conds));
    }

    private String bridgedNames() {
        return tr.units.values().stream().filter(u -> u.bridged).map(u -> u.rel).collect(Collectors.joining(", "));
    }

    // ---------------------------------------------------------- pieces of declarations

    private String resultName(Fn f) {
        String r = "result";
        Set<String> names = f.params.stream().map(p -> p.name).collect(Collectors.toSet());
        while (names.contains(r)) r += "_";
        return r;
    }

    boolean hasResult(Fn f) {
        return f.retRes.kind() != Kind.VOID;
    }

    /** A parameter of safe_F: C spelling (for the .h) or C++ spelling (for the .cpp). */
    String safeParam(Fn f, Param p, boolean c) {
        Header u = f.u;
        Edits e = new Edits();
        int depth = 0;
        for (int i = p.from; i <= p.typeTo; i++) {
            Tok x = u.t(i);
            if (x.is("(")) depth++;
            if (x.is(")")) depth--;
            if (x.is("[") && u.t(u.sig(i + 1)).is("[")) {
                int end = u.skipBalanced(i) - 1;
                e.drop(i, end);
                i = end;
            } else if (tr.isDecor(x) && !CALLCONV.contains(x.text())) {
                e.drop(i, i);
            } else if (x.is("&") && depth == 0) {          // in C++ a function type keeps its references
                if (p.constRefValue) e.drop(i, i); else e.replace.put(i, "*");
            }
        }
        if (c) tr.cview.typeEdits(u, e, p.from, p.typeTo, true);
        List<String> ws = u.words(p.from, p.typeTo, e);
        if (p.byValueStruct) {
            int at = p.nameIdx >= 0 ? ws.lastIndexOf(u.t(p.nameIdx).text()) : ws.size();
            if (at < 0) at = ws.size();
            ws.add(at, "*");
            if (!p.type.constBase()) ws.add(0, "const");
        }
        if (p.nameIdx < 0) {
            if (p.funcPtr) {
                int star = ws.indexOf("*");
                ws.add(star + 1, p.name);
            } else {
                ws.add(p.name);
            }
        } else if (!u.t(p.nameIdx).text().equals(p.name)) {
            int at = ws.lastIndexOf(u.t(p.nameIdx).text());
            if (at >= 0) ws.set(at, p.name);
        }
        return Header.joinWords(ws);
    }

    /** The return type of F as written (C++) or in C, with references as pointers. */
    String retType(Fn f, boolean c) {
        Header u = f.u;
        Edits e = new Edits();
        List<String> ws = new ArrayList<>();
        for (int i : f.retIdx) {
            Tok x = u.t(i);
            if (x.is("&")) {
                ws.add("*");
            } else if (c && (x.is("::") || x.ident() && u.t(u.sig(i + 1)).is("::"))) {
                // qualifier: dropped in C
            } else if (c && x.is("class")) {
                ws.add("struct");
            } else if (x.is("static") || x.is("inline") || x.is("constexpr")) {
                // specifiers
            } else {
                ws.add(x.text());
            }
        }
        return Header.joinWords(ws);
    }

    private static String pointerTo(String type, String name) {
        return type + (type.endsWith("*") ? "*" : " *") + name;
    }

    /** "int addCamera(Camera& camera, Camera* cameras)": the provider's declaration, for docs and RecordGen. */
    String wraps(Fn f) {
        Header u = f.u;
        Edits re = new Edits();
        int rf = f.retIdx.get(0), rt = f.retIdx.get(f.retIdx.size() - 1);
        for (int i = rf; i <= rt; i++) if (!f.retIdx.contains(i)) re.drop(i, i);
        StringBuilder b = new StringBuilder(u.render(rf, rt, re).replaceAll("\\s+", " "));
        b.append(' ').append(f.qualified()).append('(');
        int n = 0;
        for (Param p : f.params) {
            Edits e = new Edits();
            for (int j = p.from; j <= p.typeTo; j++) {
                Tok x = u.t(j);
                if (x.kind() == K.COMMENT) {
                    e.drop(j, j);
                } else if (x.is("[") && u.t(u.sig(j + 1)).is("[")) {
                    int end = u.skipBalanced(j) - 1;
                    e.drop(j, end);
                    j = end;
                } else if (tr.isDecor(x) && !CALLCONV.contains(x.text())) {
                    e.drop(j, j);
                }
            }
            if (p.nameIdx >= 0 && !u.t(p.nameIdx).text().equals(p.name)) e.replace.put(p.nameIdx, p.name);
            String s = u.render(p.from, p.typeTo, e).replaceAll("\\s+", " ").strip();
            if (p.nameIdx < 0) s = p.funcPtr ? s.replaceFirst("\\(\\s*\\*", "(*" + p.name) : s + " " + p.name;
            b.append(n++ > 0 ? ", " : "").append(s);
        }
        if (f.variadic) b.append(n > 0 ? ", " : "").append("...");
        return b.append(')').toString();
    }

    private String condOpen(List<String> conds) {
        return conds.isEmpty() ? "" : "#if " + String.join(" && ", conds) + "\n";
    }

    private String condClose(List<String> conds) {
        return conds.isEmpty() ? "" : "#endif\n";
    }

    String safeParams(Fn f, boolean c) {
        List<String> ps = new ArrayList<>();
        for (Param p : f.params) ps.add(safeParam(f, p, c));
        if (hasResult(f)) ps.add(pointerTo(retType(f, c), resultName(f)));
        return ps.isEmpty() ? (c ? "void" : "") : String.join(", ", ps);
    }

    /** An --array-params parameter: the wrapper rejects NULL for it. */
    boolean required(Fn f, Param p) {
        return tr.arrayParams.contains(f.name + "." + p.name) || tr.arrayParams.contains(p.name)
                || tr.arrayParams.contains(f.qualified() + "." + p.name);
    }
}
