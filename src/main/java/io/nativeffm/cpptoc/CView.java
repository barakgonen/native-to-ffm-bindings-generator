package io.nativeffm.cpptoc;

import io.nativeffm.cpptoc.Ast.*;
import io.nativeffm.cpptoc.Lexer.K;
import io.nativeffm.cpptoc.Lexer.Tok;

import java.nio.file.Path;
import java.util.*;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

import static io.nativeffm.cpptoc.Lexer.EOF;
import static io.nativeffm.cpptoc.Words.*;

/**
 * Renders the C view of a header: each Item as C text. References become pointers, namespaces and C++-only
 * members disappear, enum class becomes a C enum (or an integer typedef with constants), constexpr becomes
 * #define, nested types are hoisted out of their struct; everything else (comments, layout) is kept as written.
 */
final class CView {

    private final Translation tr;

    CView(Translation tr) {
        this.tr = tr;
    }

    /** The C view of header u: its items rendered in source order, under a comment and an include guard. */
    String header(Header u) {
        StringBuilder body = new StringBuilder();
        int prevEnd = 0;
        for (Item it : u.items) {
            body.append(u.src, prevEnd, u.toks.get(it.first).start());
            String text = it.render.apply(it);
            if (text != null && !text.isEmpty()) {
                if (text.startsWith("#") && !body.isEmpty() && body.charAt(body.length() - 1) != '\n') {
                    int nl = body.lastIndexOf("\n");
                    if (!body.substring(nl + 1).isBlank()) body.append('\n');
                    else body.setLength(nl + 1);
                }
                body.append(text);
            }
            prevEnd = u.toks.get(it.last).end();
        }
        body.append(u.src.substring(prevEnd));
        String text = body.toString().replaceAll("[ \\t]+\\n", "\n").replaceAll("\\n{3,}", "\n\n").strip();
        String guard = Translation.cHeaderName(u.rel).toUpperCase().replaceAll("[^A-Z0-9]", "_") + "_C_VIEW";
        StringBuilder b = new StringBuilder();
        b.append("/* ").append(Translation.cHeaderName(u.rel)).append(" - C view of ").append(u.rel)
                .append(", generated by CppToC. Do not edit: change the C++ header and rebuild.\n");
        b.append(" * The same types, constants and macros, declared in C: references are pointers, namespaces and"
                + " C++-only members are\n");
        if (u.bridged) {
            b.append(" * left out. Only functions with C linkage are declared; ")
                    .append("every function, C++ ones included, is in the safe wrapper API\n * (" + tr.baseName + "_safe.h).")
                    .append(" */\n");
        } else {
            b.append(" * left out. Not bridged to Java: converted because " + String.join(", ", u.neededBy)
                    + " use(s) " + String.join(", ", u.neededFor) + ". */\n");
        }
        b.append("#ifndef ").append(guard).append('\n');
        b.append("#define ").append(guard).append("\n\n");
        if (u.needsStdbool) b.append("#include <stdbool.h>\n\n");
        b.append(text).append("\n\n#endif /* ").append(guard).append(" */\n");
        return b.toString();
    }

    String struct(StructDef s, int itemLast) {
        Header u = s.u;
        StringBuilder pre = new StringBuilder();
        for (Object h : s.hoisted) {
            String text = hoisted(h);
            if (text != null) pre.append(text).append("\n\n");
        }
        String kwC = s.isUnion ? "union" : "struct";
        for (StructDef f : s.forwards) {                      // members that point to s itself or a later struct
            if (f.forwardDeclared) continue;
            f.forwardDeclared = true;
            pre.append("typedef ").append(f.isUnion ? "union" : "struct").append(' ').append(f.tag).append(' ')
                    .append(f.cName).append(";\n");
        }
        if (s.opaque != null) {
            return pre + "typedef " + kwC + " " + s.cName + " " + s.cName + ";   /* opaque in C: " + s.opaque + " */";
        }
        Edits e = s.e.copy();
        for (int[] r : s.typeRanges) typeEdits(u, e, r[0], r[1], true);   // a & left is in a function type
        for (int[] r : s.exprRanges) exprEdits(u, e, r[0], r[1], s.local);
        int from = s.hoistFrom >= 0 ? s.hoistFrom : s.first;
        if (s.typedefForm) {
            e.replace.put(s.kwIdx, kwC);
            e.drop(u.sig(s.kwIdx + 1), s.open - 1);
            if (s.tag != null) e.after.put(s.kwIdx, " " + s.tag);
            return pre + dedent(u, u.render(from, itemLast, e), from);
        }
        e.drop(s.declFrom, s.declTo);
        if (s.forwardDeclared) {                               // typedef written above: struct Node {...};
            e.replace.put(s.kwIdx, kwC + " " + s.cName);
            e.replace.put(s.close, "}");
        } else {
            e.replace.put(s.kwIdx, "typedef " + kwC + " " + s.cName);
            e.replace.put(s.close, "} " + s.cName);
        }
        e.drop(u.sig(s.kwIdx + 1), s.open - 1);
        int to = s.outer != null ? s.close : itemLast;
        return pre + dedent(u, u.render(from, to, e), from) + (s.outer != null ? ";" : "");
    }

    /** Removes the indentation a hoisted nested definition had inside its struct. */
    String dedent(Header u, String text, int from) {
        int lineStart = u.src.lastIndexOf('\n', u.t(from).start()) + 1;
        String indent = u.src.substring(lineStart, u.t(from).start());
        if (indent.isEmpty() || !indent.isBlank()) return text;
        return text.replace("\n" + indent, "\n");
    }

    String enumeration(EnumDef en, int itemLast) {
        Header u = en.u;
        Edits e = new Edits();
        if (en.scopedIdx >= 0) e.drop(en.scopedIdx, en.scopedIdx);
        if (en.colonIdx >= 0) e.drop(en.colonIdx, en.underTo);
        for (int[] c : en.constants) {
            e.replace.put(c[0], en.cNames.get(u.t(c[0]).text()));
            if (c[2] >= 0) exprEnumEdits(en, e, c[2], c[3]);
        }
        int from = en.hoistFrom >= 0 ? en.hoistFrom : en.first;
        int to = en.outer != null ? en.close : itemLast;
        String end = en.outer != null ? ";" : "";
        if (en.outer != null) return dedent(u, enumBody(en, e, from, to), from) + end;
        return enumBody(en, e, from, to);
    }

    String enumBody(EnumDef en, Edits e, int from, int to) {
        Header u = en.u;
        String end = "";
        if (en.cName == null) return u.render(from, to, e) + end;   // enum { A, B };
        if (en.small) {
            e.replace.put(en.kwIdx, "typedef " + en.underlying + " " + en.cName + ";\nenum");
            if (en.tagIdx >= 0) e.drop(en.tagIdx, en.tagIdx);
            e.drop(en.close + 1, en.semi - 1);
            if (en.typedefForm) e.drop(en.first, en.kwIdx - 1);
            return u.render(from, to, e) + end;
        }
        if (en.typedefForm) return u.render(from, to, e) + end;
        e.replace.put(en.kwIdx, "typedef enum");
        e.drop(en.close + 1, en.semi - 1);
        e.replace.put(en.close, "} " + en.cName);
        return u.render(from, to, e) + end;
    }

    String typedef(TypedefDef td, int itemLast) {
        Header u = td.u;
        if (td.unsupported != null) {
            return "/* [CppToC] not translated (" + td.unsupported + "): " + u.summary(td.first, td.semi)
                    .replace("*/", "* /") + " */";
        }
        Edits e = new Edits();
        if (!td.using) {
            typeEdits(u, e, td.first, td.semi, true);
            return u.render(td.first, td.outer != null ? td.semi : itemLast, e);
        }
        typeEdits(u, e, td.typeFrom, td.typeTo, true);
        String type = Header.joinWords(u.words(td.typeFrom, td.typeTo, e));
        String name = td.names.get(0);
        String text;
        if (type.matches(".*\\(\\s*\\*\\s*\\).*")) text = "typedef " + type.replaceFirst("\\(\\s*\\*\\s*\\)", "(*" + name + ")") + ";";
        else if (type.matches(".*\\[.*\\]$")) text = "typedef " + type.replaceFirst("(\\[.*\\])$", name + "$1") + ";";
        else text = "typedef " + type + " " + name + ";";
        if (td.outer != null) return text;
        Edits all = new Edits();
        all.replace.put(td.first, text);
        all.drop(td.first + 1, td.semi);
        return u.render(td.first, itemLast, all);
    }

    String constants(List<ConstDef> defs, Item it) {
        Header u = defs.get(0).u;
        StringBuilder b = new StringBuilder();
        for (ConstDef c : defs) {
            String v = constValueText(c);
            if (v == null) {
                b.append(b.isEmpty() ? "" : "\n").append("/* [CppToC] constant ").append(c.bare)
                        .append(" not translated (no C value) */");
                continue;
            }
            b.append(b.isEmpty() ? "" : "\n").append("#define ").append(c.cName).append(' ').append(v);
        }
        Edits e = new Edits();
        e.replace.put(it.first, b.toString());
        e.drop(it.first + 1, defs.get(0).last);
        return u.render(it.first, it.last, e);
    }

    String function(Fn f, int itemLast) {
        Header u = f.u;
        String proto = u.summary(f.first, f.close).replace("*/", "* /");
        if (f.problem != null) return "/* [CppToC] not translated (" + f.problem + "): " + proto + " */";
        if (!f.cView) {
            String why = !f.cLinkage ? "has C++ linkage" : f.hasBody || f.isInline ? "is inline"
                    : f.isStatic ? "is static" : f.variadic ? "is variadic" : "is not representable in C";
            String use = f.safe ? ": call " + f.safeName + "() in " + tr.baseName + "_safe.h" : "";
            return "/* " + f.qualified() + "() " + why + ", so it is not declared here" + use + " */";
        }
        Edits e = new Edits();
        if (f.externIdx >= 0) e.drop(f.externIdx, u.sig(f.externIdx + 1));
        typeEdits(u, e, f.first, f.close, true);
        for (Param p : f.params) if (p.eqIdx >= 0) e.drop(p.eqIdx, p.to);
        int j = u.sig(f.close + 1);
        while (j < f.last) {
            Tok x = u.t(j);
            if (x.is("noexcept") || x.is("throw")) {
                int k = u.sig(j + 1);
                int end = u.t(k).is("(") ? u.skipBalanced(k) - 1 : j;
                e.drop(j, end);
                j = u.sig(end + 1);
            } else if (x.is("[") && u.t(u.sig(j + 1)).is("[")) {
                int end = u.skipBalanced(j) - 1;
                e.drop(j, end);
                j = u.sig(end + 1);
            } else {
                j = u.sig(j + 1);
            }
        }
        if (f.params.isEmpty() && !f.variadic && u.sig(f.open + 1) == f.close) e.after.put(f.open, "void");
        return u.render(f.first, itemLast, e);
    }

    // ---------------------------------------------------------- edits shared by the renderers

    /** C spelling of the types in [from, to]: qualifiers and attributes removed, references as pointers. */
    void typeEdits(Header u, Edits e, int from, int to, boolean refToPtr) {
        for (int i = from; i <= to && i < u.n; i++) {
            Tok x = u.t(i);
            if (x.kind() == K.COMMENT || e.drop.get(i)) continue;
            if (x.is("[") && u.t(u.sig(i + 1)).is("[")) {
                int end = u.skipBalanced(i) - 1;
                e.drop(i, end);
                i = end;
            } else if (x.is("[")) {
                int end = u.skipBalanced(i) - 1;
                if (end > i + 1) exprEdits(u, e, u.sig(i + 1), u.prevSig(end), Map.of());
                i = end;
            } else if (x.is("::")) {
                e.drop(i, i);
            } else if (x.ident() && u.t(u.sig(i + 1)).is("::")) {
                e.drop(i, i);                                              // ns::, Outer::, std::
            } else if (x.is("alignas")) {
                e.replace.put(i, "_Alignas");
            } else if (x.is("&") && refToPtr) {
                e.replace.put(i, "*");
            } else if (x.is("class")) {
                e.replace.put(i, "struct");
            } else if (x.is("typename") || x.is("mutable")) {
                e.drop(i, i);
            } else if (x.is("nullptr")) {
                e.replace.put(i, "0");
            } else if (x.is("bool")) {
                u.needsStdbool = true;
            }
        }
    }

    /** C spelling of a constant expression; falls back to its value if it uses C++ (casts, scoped names). */
    void exprEdits(Header u, Edits e, int from, int to, Map<String, String> local) {
        boolean cxx = false;
        for (int i = from; i <= to; i++) {
            Tok x = u.t(i);
            if (x.kind() == K.COMMENT) continue;
            if (x.ident() || x.is("::")) {
                int j = i;
                StringBuilder q = new StringBuilder();
                List<Integer> parts = new ArrayList<>();
                while (j <= to && (u.t(j).ident() || u.t(j).is("::"))) {
                    if (u.t(j).ident() && !q.isEmpty() && !q.toString().endsWith("::")) break;
                    q.append(u.t(j).text());
                    parts.add(j);
                    j = u.sig(j + 1);
                }
                String name = q.toString().replaceFirst("^::", "");
                String c = local.get(name);
                if (c == null) {
                    Sym s = tr.syms.get(name);
                    c = s != null ? s.cName : name.replaceFirst(".*::", "");
                }
                if (name.equals("true") || name.equals("false")) c = name.equals("true") ? "1" : "0";
                if (Set.of("static_cast", "reinterpret_cast", "const_cast", "nullptr", "sizeof", "alignof")
                        .contains(name)) {
                    cxx = !name.equals("sizeof");
                    c = name.equals("nullptr") ? "0" : name;
                }
                e.replace.put(parts.get(0), c);
                for (int k = 1; k < parts.size(); k++) e.drop(parts.get(k), parts.get(k));
                i = parts.get(parts.size() - 1);
            } else if (x.kind() == K.NUMBER && (x.text().contains("'") || x.text().matches("0[bB].*"))) {
                Long v = ConstEval.parseNumber(x.text());
                if (v != null) e.replace.put(i, v.toString());
            } else if (x.is("{") || x.is("<")) {
                cxx = true;
            }
        }
        if (cxx) {
            Long v = tr.evaluate(ConstEval.sigToks(u, from, to), local.isEmpty() ? Map.of() : localSyms(local));
            if (v != null) {
                e.replace.put(from, v.toString());
                e.drop(from + 1, to);
            } else {
                tr.warn(u, from, "constant expression with C++ syntax could not be evaluated: " + u.summary(from, to));
            }
        }
    }

    Map<String, Sym> localSyms(Map<String, String> local) {
        Map<String, Sym> r = new HashMap<>();
        for (var en : local.entrySet()) {
            Sym s = tr.syms.get(en.getValue());
            if (s != null) r.put(en.getKey(), s);
        }
        return r;
    }

    void exprEnumEdits(EnumDef en, Edits e, int from, int to) {
        Map<String, String> local = new HashMap<>(en.cNames);
        exprEdits(en.u, e, from, to, local);
    }

    String hoisted(Object h) {
        if (h instanceof StructDef s) return struct(s, s.close);
        if (h instanceof EnumDef en) return enumeration(en, en.close);
        if (h instanceof TypedefDef td) return typedef(td, td.semi);
        if (h instanceof ConstDef c) {
            String v = constValueText(c);
            return v == null ? null : "#define " + c.cName + " " + v;
        }
        return null;
    }

    String constValueText(ConstDef c) {
        Header u = c.u;
        List<Tok> ts = ConstEval.sigToks(u, c.exprFrom, c.exprTo);
        if (ts.size() == 1 && (ts.get(0).kind() == K.STRING || ts.get(0).kind() == K.CHAR)) return ts.get(0).text();
        if (ts.size() == 1 && ts.get(0).kind() == K.NUMBER) {
            String num = ts.get(0).text();
            if (num.contains("'") || num.matches("0[bB].*")) {
                Long v = ConstEval.parseNumber(num);
                return v == null ? num.replace("'", "") : v.toString();
            }
            return num;
        }
        Long v = tr.evaluate(ts, c.outer != null ? localSyms(c.outer.local) : Map.of());
        Edits e = new Edits();
        exprEdits(u, e, c.exprFrom, c.exprTo, c.outer != null ? c.outer.local : Map.of());
        String text = u.render(c.exprFrom, c.exprTo, e).replaceAll("\\s+", " ").strip();
        if (text.matches("[\\w\\s+\\-*/%()<>|&^~!.,'\"?:]*") && !text.contains("::")) {
            return text.matches("-?\\w+|\"[^\"]*\"") ? text : "(" + text + ")";
        }
        return v == null ? null : v.toString();
    }
}
