package io.nativeffm.recordgen;

import io.nativeffm.recordgen.Api.ApiFunction;
import io.nativeffm.recordgen.Api.ApiParam;
import io.nativeffm.recordgen.Api.Facade;
import io.nativeffm.recordgen.Api.ParamKind;
import io.nativeffm.recordgen.Api.RetKind;

import java.util.*;

/**
 * Writes an API class: its #define constants, and for each wrapper function a static method that converts the Java
 * arguments (records to native memory in per-thread scratch memory, NativeArrays as they are), calls the wrapper
 * function, hands a failure to SafeWrapper, copies in/out arguments back and converts the result.
 */
final class ApiWriter {

    private final String pkg, base;
    private final boolean types;

    /** pkg: the api package; base: the base package (pkg is base.api); types: whether base.types has classes. */
    ApiWriter(String pkg, String base, boolean types) {
        this.pkg = pkg;
        this.base = base;
        this.types = types;
    }

    /** The source of an API class: its constants, and a static method per function. */
    String write(Facade fa) {
        String headers = String.join(", ", fa.headers().stream().map(h -> "{@code " + h + "}").toList());
        StringBuilder b = new StringBuilder("""
                // Generated by RecordGen from jextract output. Do not edit.
                package %1$s;

                import %2$s.internal.RecordSupport;
                import %2$s.internal.SafeCalls;
                import %2$s.runtime.*;
                %3$s
                import java.lang.foreign.*;
                import java.util.Objects;

                /**
                """.formatted(pkg, base, types ? "import " + base + ".types.*;\n" : ""));
        if (fa.functions().isEmpty()) {
            b.append("""
                     * The constants of %1$s.
                     */
                    public final class %2$s {

                    """.formatted(headers, fa.name()));
            constants(fa, b);
            return b.append("    private ").append(fa.name()).append("() {\n    }\n}\n").toString();
        }
        b.append("""
                 * The functions and constants of %1$s, taking and returning Java objects.
                 * <p>
                 * Arguments are copied to per-thread scratch memory that is reused once the call returns, so these methods
                 * must not be used with functions that keep such a pointer after they return (NativeArray arguments are
                 * the exception: they are Java-managed memory). Call the jextract method directly for those.
                 * <p>
                 * Every provider function is called through the safe wrapper: a C++ exception, or a NULL where the
                 * provider takes a reference, never reaches the JVM. The safe wrapper reports it as a {@link SafeError}, and the
                 * error handler decides what happens: by default ({@link SafeErrorHandler#THROW}) the method throws a
                 * {@link SafeException}. Set another one with {@link SafeWrapper#setErrorHandler}, or for a block of code
                 * with {@link SafeWrapper#runWithErrorHandler}. If the handler returns, the method returns 0, {@code false}
                 * or {@code null}.
                 * <p>
                 * Loading this class compares every struct layout with the C++ compiler's ({@link SafeWrapper#verifyLayouts()}).
                 */
                public final class %2$s {

                """.formatted(headers, fa.name()));
        constants(fa, b);
        b.append("""
                    static {
                        SafeCalls.load();                   // loads the libraries, checks the struct layouts: once
                    }

                    private %s() {
                    }
                """.formatted(fa.name()));
        for (ApiFunction fn : fa.functions()) {
            method(fn, false, b);
            if (fn.params().stream().anyMatch(p -> p.kind() == ParamKind.STRUCT_PTR)) method(fn, true, b);
        }
        return b.append("}\n").toString();
    }

    private void constants(Facade fa, StringBuilder b) {
        for (var d : fa.constants().entrySet()) {
            String n = Types.RESERVED.contains(d.getKey()) ? d.getKey() + "_" : d.getKey();
            long v = d.getValue();
            b.append("    /** {@code #define ").append(d.getKey()).append(' ').append(v).append("} */\n");
            b.append("    public static final ").append(v == (int) v ? "int " : "long ").append(n).append(" = ")
                    .append(v).append(v == (int) v ? "" : "L").append(";\n");
        }
        if (!fa.constants().isEmpty()) b.append('\n');
    }

    /** One method; refs: the overload with Ref<S> for the non-const struct pointers (in/out). */
    private void method(ApiFunction fn, boolean refs, StringBuilder b) {
        String in1 = "    ", in2 = in1 + "    ", in3 = in2 + "    ";
        // javadoc
        b.append('\n').append(in1).append("/**\n");
        b.append(in1).append(" * Calls {@snippet lang=c : ").append(fn.prototype().replace("*/", "* /")).append(" }\n");
        b.append(in1).append(" * through the safe wrapper ({@code ").append(fn.cName()).append("}): failures go to the error"
                + " handler.\n");
        for (ApiParam p : fn.params()) {
            String note = switch (p.kind()) {
                case STRUCT_PTR -> refs
                        ? "copied to native memory before the call, and replaced with the struct's contents after it"
                          + " (an empty {@code Ref} passes a zeroed struct)"
                        : "copied to native memory for the call; changes the function makes are discarded"
                          + " (use the {@code Ref} overload to get them); "
                          + (p.reference() ? "not null (a C++ reference)" : "{@code null} passes {@code NULL}");
                case STRUCT_CONST_PTR -> p.reference() ? "copied to native memory for the call (a C++ reference: not null)"
                        : "copied to native memory for the call; {@code null} passes {@code NULL}";
                case STRUCT_ARRAY -> "Java-managed native memory, passed to the function as is (not copied)"
                        + (p.minSize() > 0 ? "; must hold at least " + p.minSize() + " elements" : "");
                case STRING -> "copied to a NUL-terminated UTF-8 string for the call; {@code null} passes {@code NULL}";
                case PRIM_REF -> "in/out: its value is passed to the function (an empty {@code Ref} passes 0) and"
                        + " replaced with what the function wrote";
                case PTR_REF -> "in/out pointer: an empty {@code Ref} passes {@code NULL}; after the call it holds the"
                        + " pointer the function wrote (a zero-length segment: use {@code reinterpret(size)} to read it)";
                case PRIM_ARRAY -> (p.readOnly() ? "copied to native memory for the call"
                        : "copied to native memory for the call, and back into the array after it (in/out)")
                        + (p.minSize() > 0 ? "; at least " + p.minSize() + " elements" : "") + "; not null";
                case PASS, ENUM -> null;
            };
            if (note != null) b.append(in1).append(" * @param ").append(p.javaName()).append(' ').append(note).append('\n');
        }
        String retNote = switch (fn.ret()) {
            case STRUCT_PTR -> "a copy of the struct the result points to, or {@code null} for {@code NULL}"
                    + " (the native memory is not freed)";
            case STRING -> "a copy of the returned string, or {@code null} for {@code NULL}";
            case STRUCT_VALUE -> "the returned struct";
            default -> null;
        };
        if (retNote != null) b.append(in1).append(" * @return ").append(retNote).append('\n');
        b.append(in1).append(" * @throws SafeException if the function fails and the error handler is {@link"
                + " SafeErrorHandler#THROW}\n");
        b.append(in1).append(" */\n");

        // signature
        String retType = switch (fn.ret()) {
            case VOID -> "void";
            case PASS -> simpleType(fn.retType());
            case ENUM -> fn.retEnum().javaName;
            case STRUCT_VALUE, STRUCT_PTR -> fn.retStruct().ref();
            case STRING -> "String";
        };
        StringJoiner sig = new StringJoiner(", ");
        for (ApiParam p : fn.params()) {
            String t = switch (p.kind()) {
                case PASS -> simpleType(p.javaType());
                case ENUM -> p.enumInfo().javaName;
                case STRING -> "String";
                case STRUCT_PTR -> refs ? "Ref<" + p.struct().ref() + ">" : p.struct().ref();
                case STRUCT_CONST_PTR -> p.struct().ref();
                case STRUCT_ARRAY -> "NativeArray<" + p.struct().ref() + ">";
                case PRIM_REF -> "Ref<" + box(p.cell().carrier()) + ">";
                case PTR_REF -> "Ref<MemorySegment>";
                case PRIM_ARRAY -> p.cell().carrier().getSimpleName() + "[]";
            };
            sig.add(t + " " + p.javaName());
        }
        b.append(in1).append("public static ").append(retType).append(' ').append(fn.javaName())
                .append('(').append(sig).append(") {\n");

        // body
        boolean needsArena = fn.ret() == RetKind.STRUCT_VALUE || fn.resultCell() != null || fn.params().stream().anyMatch(
                p -> p.kind() != ParamKind.PASS && p.kind() != ParamKind.ENUM && p.kind() != ParamKind.STRUCT_ARRAY);
        String in = needsArena ? in3 : in2;
        if (needsArena) {   // per-thread scratch memory, released when the call returns: no malloc/free per call
            b.append(in2).append("RecordSupport.Scratch arena$ = RecordSupport.Scratch.current();\n");
            b.append(in2).append("long mark$ = arena$.mark();\n");
            b.append(in2).append("try {\n");
        }
        // When the call gets a Java-managed array, C may copy the other structs into it; whatever their pointer
        // fields point to must then live as long as the array, so it is allocated in the array's arena.
        // The array of the same struct type is preferred (a Lidar goes into the lidars array), else the first one.
        List<ApiParam> arrays = fn.params().stream().filter(p -> p.kind() == ParamKind.STRUCT_ARRAY).toList();
        Map<ApiParam, String> pointeesOf = new HashMap<>();
        if (needsArena && !arrays.isEmpty()) {
            for (ApiParam a : arrays) {
                b.append(in).append("SegmentAllocator ").append(a.javaName()).append("$pointees = RecordSupport.allocatorOf(")
                        .append(a.javaName()).append(", \"").append(a.javaName()).append("\");\n");
            }
            for (ApiParam p : fn.params()) {
                ApiParam home = arrays.stream().filter(a -> a.struct() == p.struct()).findFirst().orElse(arrays.get(0));
                pointeesOf.put(p, home.javaName() + "$pointees");
            }
        }
        List<String> after = new ArrayList<>();          // copy in/out values back, before the scratch memory is released
        StringJoiner args = new StringJoiner(", ");
        for (ApiParam p : fn.params()) {
            String n = p.javaName();
            String pointees = pointeesOf.getOrDefault(p, "arena$");
            switch (p.kind()) {
                case PASS -> args.add(n);
                case ENUM -> args.add("Objects.requireNonNull(" + n + ", \"" + n + "\").value()");
                case STRING -> args.add("RecordSupport.cString(" + n + ", arena$)");
                case STRUCT_CONST_PTR -> args.add("RecordSupport.valueIn(" + nonNull(p) + ", " + p.struct().ref()
                        + ".LAYOUT, arena$, " + pointees + ")");
                case STRUCT_ARRAY -> args.add("RecordSupport.arrayArg(" + n + ", " + p.minSize() + ", \"" + n + "\")");
                case PRIM_REF -> {
                    String layout = p.cell().layoutExpr(), boxed = box(p.cell().carrier());
                    b.append(in).append(boxed).append(' ').append(n).append("$v = Objects.requireNonNull(").append(n)
                            .append(", \"").append(n).append("\").get();\n");
                    b.append(in).append("MemorySegment ").append(n).append("$ = arena$.allocate(").append(layout).append(");\n");
                    b.append(in).append(n).append("$.set(").append(layout).append(", 0, ").append(n).append("$v == null ? ")
                            .append(zero(p.cell().carrier())).append(" : ").append(n).append("$v);\n");
                    args.add(n + "$");
                    after.add(n + ".set(" + n + "$.get(" + layout + ", 0));");
                }
                case PRIM_ARRAY -> {
                    String layout = p.cell().layoutExpr();
                    b.append(in).append("MemorySegment ").append(n).append("$ = RecordSupport.primitivesIn(").append(n)
                            .append(", ").append(layout).append(", ").append(p.minSize()).append(", \"").append(n)
                            .append("\", arena$);\n");
                    args.add(n + "$");
                    if (!p.readOnly()) after.add("RecordSupport.primitivesOut(" + n + "$, " + n + ", " + layout + ");");
                }
                case PTR_REF -> {
                    b.append(in).append("MemorySegment ").append(n).append("$ = arena$.allocate(ValueLayout.ADDRESS);\n");
                    b.append(in).append(n).append("$.set(ValueLayout.ADDRESS, 0, RecordSupport.orNull(Objects.requireNonNull(")
                            .append(n).append(", \"").append(n).append("\").get()));\n");
                    args.add(n + "$");
                    after.add(n + ".set(" + n + "$.get(ValueLayout.ADDRESS, 0));");
                }
                case STRUCT_PTR -> {
                    if (refs) {
                        b.append(in).append("MemorySegment ").append(n).append("$ = RecordSupport.inOut(").append(n)
                                .append(", ").append(p.struct().ref()).append(".LAYOUT, arena$, ").append(pointees)
                                .append(");\n");
                        args.add(n + "$");
                        after.add(n + ".set(" + p.struct().ref() + ".from(" + n + "$));");
                    } else {
                        args.add("RecordSupport.valueIn(" + nonNull(p) + ", " + p.struct().ref() + ".LAYOUT, arena$, "
                                + pointees + ")");
                    }
                }
            }
        }
        safeCall(fn, args, after, in, b);
        if (needsArena) {
            b.append(in2).append("} finally {\n");
            b.append(in3).append("arena$.release(mark$);\n");
            b.append(in2).append("}\n");
        }
        b.append(in1).append("}\n");
    }

    /** The call of a wrapper function: status check, error handler, copy-backs, result. */
    private void safeCall(ApiFunction fn, StringJoiner args, List<String> after, String in, StringBuilder b) {
        String inner = in + "    ";
        if (fn.resultCell() != null) {
            b.append(in).append("MemorySegment result$ = arena$.allocate(").append(fn.resultCell()).append(");\n");
            args.add("result$");
        }
        b.append(in).append("int status$ = ").append(fn.declaring().getName()).append('.').append(fn.method())
                .append('(').append(args).append(");\n");
        String failed = switch (fn.ret()) {
            case VOID -> "";
            case PASS -> fn.retType().isPrimitive() ? " " + zero(fn.retType()) : " null";
            default -> " null";
        };
        b.append(in).append("if (status$ != 0) {\n");
        b.append(inner).append("SafeCalls.fail(status$, \"").append(fn.provider()).append("\");\n");
        b.append(inner).append("return").append(failed).append(";\n");
        b.append(in).append("}\n");
        for (String a : after) b.append(in).append(a).append('\n');
        String cell = fn.resultCell();
        String value = switch (fn.ret()) {
            case VOID -> null;
            case PASS -> "result$.get(" + cell + ", 0)";
            case ENUM -> fn.retEnum().javaName + ".of(result$.get(ValueLayout.JAVA_INT, 0))";
            case STRUCT_VALUE -> fn.retStruct().ref() + ".from(result$)";
            case STRUCT_PTR -> fn.retStruct().ref() + ".fromPointer(result$.get(ValueLayout.ADDRESS, 0))";
            case STRING -> "RecordSupport.readCString(result$.get(ValueLayout.ADDRESS, 0))";
        };
        if (value != null) b.append(in).append("return ").append(value).append(";\n");
    }

    /** A reference parameter must not be NULL: check it in Java instead of crashing in C++. */
    private static String nonNull(ApiParam p) {
        return p.reference() ? "Objects.requireNonNull(" + p.javaName() + ", \"" + p.javaName() + "\")" : p.javaName();
    }

    private static String zero(Class<?> carrier) {
        return switch (carrier.getName()) {
            case "boolean" -> "false";
            case "long" -> "0L";
            case "float" -> "0f";
            case "double" -> "0.0";
            case "char" -> "'\\0'";
            case "byte" -> "(byte) 0";
            case "short" -> "(short) 0";
            default -> "0";
        };
    }

    private static String simpleType(Class<?> c) {
        return c.isPrimitive() || c.getPackageName().equals("java.lang.foreign") || c.getPackageName().equals("java.lang")
                ? c.getSimpleName() : c.getCanonicalName();
    }

    static String box(Class<?> c) {
        return switch (c.getName()) {
            case "int" -> "Integer";
            case "char" -> "Character";
            default -> Character.toUpperCase(c.getName().charAt(0)) + c.getName().substring(1);
        };
    }
}
