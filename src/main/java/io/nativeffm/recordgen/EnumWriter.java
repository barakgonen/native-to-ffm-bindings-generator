package io.nativeffm.recordgen;

import io.nativeffm.recordgen.Types.EnumInfo;

import java.util.*;

/** Writes a Java enum for a C enum: its constants with their C values, value(), of(int) and ofOrNull(int). */
final class EnumWriter {

    private final String pkg, base;

    /** pkg: the types package; base: the base package (pkg is base.types). */
    EnumWriter(String pkg, String base) {
        this.pkg = pkg;
        this.base = base;
    }

    /** The source of the Java enum for C enum e. */
    String write(EnumInfo e) {
        StringJoiner constants = new StringJoiner(",\n", "", ";");
        e.constants.forEach((n, v) -> constants.add("    " + n + "(" + v + ")"));
        StringBuilder cases = new StringBuilder();
        Set<Integer> seen = new HashSet<>();
        e.constants.forEach((n, v) -> {
            if (seen.add(v)) cases.append("            case ").append(v).append(" -> ").append(n).append(";\n");
        });
        return """
                // Generated by RecordGen from jextract output. Do not edit.
                package %1$s;

                import %6$s.runtime.NativeEnum;

                /** Java enum for the C enum {@code %2$s}. */
                public enum %3$s implements NativeEnum {
                %4$s

                    private final int value;

                    %3$s(int value) {
                        this.value = value;
                    }

                    /** The C value of this constant. */
                    @Override
                    public int value() {
                        return value;
                    }

                    /**
                     * The constant with the given C value.
                     *
                     * @throws IllegalArgumentException if no constant has this value
                     */
                    public static %3$s of(int value) {
                        return switch (value) {
                %5$s            default -> throw new IllegalArgumentException("no %3$s constant has the value " + value);
                        };
                    }

                    /** The constant with the given C value, or {@code null} if there is none (used when reading memory). */
                    public static %3$s ofOrNull(int value) {
                        return switch (value) {
                %5$s            default -> null;
                        };
                    }
                }
                """.formatted(pkg, e.cName, e.javaName, constants, cases, base);
    }
}
